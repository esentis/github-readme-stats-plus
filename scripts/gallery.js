// Regenerates the previews in examples/ and the STYLES.md gallery from fixed sample data: npm run gallery
import { mkdirSync, writeFileSync } from "node:fs";
import styles, { groups } from "../styles/index.js";

const repo = {
  owner: "esentis",
  name: "load_switch",
  description: "A highly customizable toggle switch with a loading state.",
  stars: "20",
  starCount: 20,
  forks: "3",
  lang: { name: "Dart", color: "#00B4AB" },
};

mkdirSync("examples", { recursive: true });
for (const [name, render] of Object.entries(styles)) writeFileSync(`examples/${name}.svg`, render(repo));

const cell = ([name, style]) =>
  `<td width="50%" valign="top"><img src="examples/${name}.svg" width="100%" alt="${name} style" /><br /><code>${name}</code> ${style.about}</td>`;

let page = `# Styles

All ${Object.keys(styles).length} styles, rendered with sample data. Pick one with \`&style=<name>\`. The default is \`adaptive\`.

<!-- Generated by \`npm run gallery\` from the style files. Edit those, not this page. -->
`;
for (const [title, group] of Object.entries(groups)) {
  const entries = Object.entries(group);
  page += `\n## ${title}\n\n<table>\n`;
  for (let i = 0; i < entries.length; i += 2) page += `<tr>${entries.slice(i, i + 2).map(cell).join("")}</tr>\n`;
  page += "</table>\n";
}
writeFileSync("STYLES.md", page);
